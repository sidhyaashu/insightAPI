import asyncio
import json
import os
import time
from pathlib import Path
from urllib.parse import urlparse

from app.sdk import AgentEngine
from app.services.openapi_exporter import OpenAPIExporter
from app.services.postman_exporter import PostmanExporter
from app.services.markdown_exporter import MarkdownExporter

# Root repository examples directory
REPO_ROOT = Path(__file__).resolve().parent.parent
EXAMPLES_DIR = REPO_ROOT / "examples"


async def crawl_and_generate_example(
    target_url: str,
    site_slug: str,
    site_title: str,
    max_pages: int,
    interesting_insight: str,
):
    print(f"\n==================================================")
    print(f"Generating Example for: {site_title} ({target_url})")
    print(f"==================================================")

    out_dir = EXAMPLES_DIR / site_slug
    out_dir.mkdir(parents=True, exist_ok=True)

    start_time = time.time()
    engine = AgentEngine(headless=True)
    res = await engine.crawl(target_url, max_pages=max_pages, rate_limit_ms=500)
    elapsed = round(time.time() - start_time, 1)

    captured = res.captured_endpoints
    rest_count = res.rest_count
    graphql_count = res.graphql_count
    ws_count = res.websocket_count

    # 1. Export OpenAPI spec
    openapi_spec = OpenAPIExporter.export_to_json(site_title, target_url, captured)
    (out_dir / "openapi.json").write_text(openapi_spec, encoding="utf-8")

    # 2. Export Postman Collection
    postman_coll = PostmanExporter.export_to_json(site_title, target_url, captured)
    (out_dir / "postman.json").write_text(postman_coll, encoding="utf-8")

    # 3. Export Markdown Docs
    markdown_docs = MarkdownExporter.generate_markdown(site_title, target_url, captured)
    (out_dir / "API_DOCS.md").write_text(markdown_docs, encoding="utf-8")

    # 4. Generate Site-Specific README.md
    readme_content = f"""# 📦 Crawl Example Output: {site_title}

> **Target Site**: `{target_url}`  
> **Autogenerated by**: [InsightAPI AI](https://github.com/your-org/InsightAPI)

This directory contains real, production-grade API documentation automatically generated by InsightAPI AI after exploring **{target_url}** with zero manual configuration.

---

## 📊 Exploration Summary

| Metric | Value |
|---|---|
| **Target URL** | [`{target_url}`]({target_url}) |
| **Pages Explored** | `{res.explored_count}` page state(s) |
| **Execution Time** | `{elapsed}s` |
| **Endpoints Discovered** | `{len(captured)}` total (`{rest_count}` REST, `{graphql_count}` GraphQL, `{ws_count}` WebSocket) |
| **OpenAPI Spec** | [`openapi.json`](openapi.json) |
| **Postman Collection** | [`postman.json`](postman.json) |
| **Markdown Documentation** | [`API_DOCS.md`](API_DOCS.md) |

---

## 💡 Autonomous Inferences & Key Discoveries

{interesting_insight}

---

## 📁 Generated Files

- 📄 **[`openapi.json`](openapi.json)**: Valid OpenAPI 3.0.3 JSON specification with merged JSON schemas, path parameters, and captured example request/response payloads.
- 🚀 **[`postman.json`](postman.json)**: Official Postman Collection v2.1 pre-filled with observed request bodies and saved example responses for instant execution.
- 📝 **[`API_DOCS.md`](API_DOCS.md)**: Clean Markdown documentation with endpoint parameter tables and sample cURL requests.
"""

    (out_dir / "README.md").write_text(readme_content.strip() + "\n", encoding="utf-8")
    print(f"✔ Successfully saved example outputs to {out_dir}")

    return {
        "title": site_title,
        "slug": site_slug,
        "url": target_url,
        "pages": res.explored_count,
        "time": elapsed,
        "endpoints": len(captured),
        "rest": rest_count,
        "graphql": graphql_count,
    }


async def main():
    EXAMPLES_DIR.mkdir(parents=True, exist_ok=True)

    summary_list = []

    # 1. ReqRes.in Example
    res1 = await crawl_and_generate_example(
        target_url="https://reqres.in",
        site_slug="reqres.in",
        site_title="ReqRes API Sandbox",
        max_pages=6,
        interesting_insight=(
            "* **Dynamic Route Parameterization**: Automatically detected and normalized dynamic numeric route paths "
            "(`https://reqres.in/api/users/2` $\\rightarrow$ `/api/users/{id}`).\n"
            "* **Cross-Example Schema Merging**: Merged JSON schemas across multiple observed response examples, "
            "correctly marking optional fields present in user detail responses versus list summaries.\n"
            "* **Payload Redaction**: Captured real HTTP request/response payloads while redacting sensitive tokens."
        ),
    )
    summary_list.append(res1)

